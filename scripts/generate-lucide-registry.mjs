#!/usr/bin/env node

import path from "node:path";
import fs from "node:fs";
import { generateLucideRegistry } from "../src/components/lucide/generate-lucide-registry-core.mjs";
const { default: sharedLucideIcons } = await import("../src/components/lucide/lucide-icons.json", {
	with: { type: "json" },
});

const ROOT = process.cwd();
const sources = [
  "src/blocks/list/index.jsx",
  "src/blocks/list-item/index.jsx",
  "src/components/controls/bullets/bullet-selector.jsx",
];
const outputFile = path.join(ROOT, "src/components/lucide/lucide-registry.js");
const iconDir = path.join(ROOT, "node_modules/lucide-react/dist/esm/icons");

const normalizeSharedIconsPayload = (raw) => {
  if (Array.isArray(raw)) {
    return { icons: raw.map((item) => String(item || "").trim()).filter(Boolean) };
  }
  if (raw && typeof raw === "object" && Array.isArray(raw.icons)) {
    return {
      icons: raw.icons.map((item) => String(item || "").trim()).filter(Boolean)
    };
  }
  return { icons: [] };
};

const tempSharedIconsFile = path.join(ROOT, ".tmp-shared-lucide-icons.json");
const sharedPayload = normalizeSharedIconsPayload(sharedLucideIcons);
fs.writeFileSync(tempSharedIconsFile, JSON.stringify(sharedPayload), "utf8");

const result = generateLucideRegistry({
  root: ROOT,
  sources,
  sharedIconsFile: tempSharedIconsFile,
  sharedIcons: sharedPayload.icons,
  outputFile,
  iconDir,
  banner: "// Auto-generated by scripts/generate-lucide-registry.mjs",
});

if (fs.existsSync(tempSharedIconsFile)) {
  fs.unlinkSync(tempSharedIconsFile);
}

if (result.missing.length > 0) {
  console.warn(`Missing Lucide icons (${result.missing.length}):`);
  for (const icon of result.missing) {
    console.warn(`- ${icon.name} -> ${icon.kebab}`);
  }
}

console.log(
  `Generated ${result.validCount} icons -> ${path.relative(ROOT, outputFile)} (shared: ${result.usedSharedIconCount}, local: ${result.usedSourceIconCount})`
);
console.log("[motto] Shared allowlist source: src/components/lucide/lucide-icons.json");
