import fs from "node:fs";
import path from "node:path";

const ICON_REGEX = /["']icon["']\s*:\s*["']([^"']+)["']/g;

export const toKebab = (name) =>
	String(name || "")
		.trim()
		.replace(/([a-z0-9])([A-Z])/g, "$1-$2")
		.replace(/([a-zA-Z])([0-9])/g, "$1-$2")
		.replace(/([0-9])([a-zA-Z])/g, "$1-$2")
		.replace(/[_\s]+/g, "-")
		.toLowerCase();

export const toVarName = (kebab) =>
	String(kebab || "")
		.split("-")
		.filter(Boolean)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join("") || "Icon";

export const parseIconsFromText = (text) => {
	const out = new Set();
	let match;
	while ((match = ICON_REGEX.exec(String(text || "")))) {
		const raw = String(match[1] || "").trim();
		if (raw) out.add(raw);
	}
	return out;
};

export const readSharedIconNames = (sharedIconsFile) => {
	if (!sharedIconsFile) return new Set();
	if (!fs.existsSync(sharedIconsFile)) return new Set();

	try {
		const data = JSON.parse(fs.readFileSync(sharedIconsFile, "utf8"));
		const list = Array.isArray(data?.icons) ? data.icons : [];
		return new Set(list.map((item) => String(item || "").trim()).filter(Boolean));
	} catch {
		return new Set();
	}
};

export const readSourceIconNames = (root, sources = []) => {
	const out = new Set();
	(sources || []).forEach((relPath) => {
		const full = path.join(root, relPath);
		if (!fs.existsSync(full)) return;
		const text = fs.readFileSync(full, "utf8");
		for (const name of parseIconsFromText(text)) out.add(name);
	});
	return out;
};

const resolveIconKebab = (name, iconDir) => {
	const primary = toKebab(name);
	const variants = [
		primary,
		primary.replace(/(\d)-x-(\d)/g, "$1x$2"),
	];

	for (const kebab of [...new Set(variants)]) {
		if (fs.existsSync(path.join(iconDir, `${kebab}.js`))) {
			return kebab;
		}
	}

	return "";
};

export const generateLucideRegistry = ({
	root,
	sources = [],
	sharedIconsFile = "",
	outputFile,
	iconDir,
	banner = "// Auto-generated by src/components/lucide/generate-lucide-registry-core.mjs",
}) => {
	if (!root) throw new Error("generateLucideRegistry: root is required.");
	if (!outputFile) throw new Error("generateLucideRegistry: outputFile is required.");
	if (!iconDir) throw new Error("generateLucideRegistry: iconDir is required.");

	const sharedNames = readSharedIconNames(sharedIconsFile);
	const sourceNames = readSourceIconNames(root, sources);
	const allIconNames = new Set([...sharedNames, ...sourceNames]);

	const valid = [];
	const missing = [];
	for (const name of [...allIconNames].sort((a, b) => a.localeCompare(b))) {
		const resolvedKebab = resolveIconKebab(name, iconDir);
		if (resolvedKebab) {
			valid.push({ name, kebab: resolvedKebab });
		} else {
			missing.push({ name, kebab: toKebab(name) });
		}
	}

	const importLines = [];
	const mapLines = [];
	const usedVarNames = new Set();

	for (const { name, kebab } of valid) {
		let varName = toVarName(kebab);
		let suffix = 2;
		while (usedVarNames.has(varName)) {
			varName = `${toVarName(kebab)}${suffix}`;
			suffix += 1;
		}
		usedVarNames.add(varName);
		importLines.push(`import ${varName} from \"lucide-react/dist/esm/icons/${kebab}.js\";`);
		mapLines.push(`\t\"${name}\": ${varName},`);
		mapLines.push(`\t\"${kebab}\": ${varName},`);
	}

	const uniqueMapLines = [...new Set(mapLines)].sort((a, b) => a.localeCompare(b));
	const output = [
		banner,
		"// Do not edit manually.",
		"",
		...importLines.sort((a, b) => a.localeCompare(b)),
		"",
		"export const LUCIDE_ICON_REGISTRY = {",
		...uniqueMapLines,
		"};",
		"",
	].join("\n");

	fs.writeFileSync(outputFile, output, "utf8");

	return {
		validCount: valid.length,
		missing,
		usedSharedIconCount: sharedNames.size,
		usedSourceIconCount: sourceNames.size,
	};
};
